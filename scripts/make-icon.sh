#!/usr/bin/env bash
#
# CapsJump's mark and its colours live here, and only here: the Caps Lock key's arrow,
# outlined as on the key, leaping up and to the right with three motion lines behind it,
# printed in graphite on a white keyboard key whose Caps Lock light is on. The key is lit
# from above: its top fades from white to a light gray, its walls darken towards the bottom,
# and it casts a soft shadow. This script writes every file that shows it:
#
#   packaging/icon.svg        the app icon on Apple's macOS grid (an 824-unit rounded square
#                                 centred on a 1024 canvas, its shadow inside the canvas);
#                                 the README shows it
#   packaging/AppIcon.icns    every size of that icon, for scripts/bundle.sh
#   packaging/menubar.svg     the mark alone in black, which macOS draws as a template image
#                                 in the menu bar's own colour, and MenuBarIcon.png and @2x;
#                                 a template image is one colour, so the key has no place there
#   site/icon.svg             the key and mark cropped to the key, with no shadow to crop:
#                                 favicon and site header
#   site/icon.png             a 180 px opaque square for iPhones (apple-touch-icon); iOS
#                                 rounds its corners itself and fills transparent pixels black
#
# The SVGs and images are committed so a build needs no SVG renderer; change the mark or a
# colour here, never in those files, and rerun this script. Needs rsvg-convert (brew install
# librsvg) and macOS's iconutil.
#
# Usage: scripts/make-icon.sh [--check]
#
# With --check it writes only the SVGs, to a temporary folder, and fails with a diff if any
# differs from the committed copy. CI runs it; it needs no renderer.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

INK="#2c2c2e"          # the mark, printed on the key
TOP_HI="#ffffff"       # the key's top, where the light falls
TOP_LO="#e9e9ec"       # and at its front edge
WALL_HI="#e4e4e7"      # the key's walls, at the top
WALL_LO="#a7a8ad"      # and at the bottom, in shade
LED_CORE="#c8ffd2"     # the Caps Lock light: its bright centre,
LED="#4fdc6f"          # its body,
LED_EDGE="#25a843"     # its rim,
GLOW="#34c759"         # and the glow around it
BACKDROP="#ededed"     # the touch icon's square behind the key
MASK="#000000"         # the menu bar's template image; only its shape counts

GENERATED='<!-- Generated by scripts/make-icon.sh, which holds the mark and its colours; edit that
     script and rerun it, never this file. -->'

# The mark, in the 256-unit space every framing below shares, filled with $1.
mark() {
  cat <<EOF
  <g fill="$1">
    <g transform="translate(128 128) scale(1.12) translate(-156 -110)">
      <path fill-rule="evenodd" transform="translate(162 86) rotate(24) scale(0.78) translate(-128 -97)" d="M128 36 L200 114 L160 114 L160 158 L96 158 L96 114 L56 114 Z M128 78 L156 104 L138 104 L138 136 L118 136 L118 104 L100 104 Z"/>
      <g transform="translate(142 130) rotate(24)">
        <rect x="-21" y="12" width="9" height="26" rx="4.5"/>
        <rect x="-4.5" y="12" width="9" height="40" rx="4.5"/>
        <rect x="12" y="12" width="9" height="26" rx="4.5"/>
      </g>
    </g>
  </g>
EOF
}

# The gradients and blurs the key is drawn with.
key_defs() {
  cat <<EOF
  <defs>
    <linearGradient id="top" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="$TOP_HI"/><stop offset="1" stop-color="$TOP_LO"/></linearGradient>
    <linearGradient id="wall" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="$WALL_HI"/><stop offset="1" stop-color="$WALL_LO"/></linearGradient>
    <radialGradient id="led"><stop offset="0" stop-color="$LED_CORE"/><stop offset="0.5" stop-color="$LED"/><stop offset="1" stop-color="$LED_EDGE"/></radialGradient>
    <filter id="shadow" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="6"/></filter>
    <filter id="glow" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="3"/></filter>
  </defs>
EOF
}

# The key with the mark printed on it, in the 256-unit space the mark uses. The walls are a
# rounded square and the top sits on them a little high, so the walls show mostly along the
# bottom; the light is in the top's corner, where a Mac keyboard puts it. With "shadow" as
# $1 the key also casts its shadow below it.
keycap() {
  if [[ "${1:-}" == "shadow" ]]; then
    echo '  <rect x="16" y="26" width="224" height="222" rx="54" fill="#000000" opacity="0.28" filter="url(#shadow)"/>'
  fi
  cat <<EOF
  <rect x="8" y="8" width="240" height="238" rx="56" fill="url(#wall)"/>
  <rect x="14" y="10" width="228" height="218" rx="50" fill="url(#top)"/>
  <rect x="14.75" y="10.75" width="226.5" height="216.5" rx="49.5" fill="none" stroke="$TOP_HI" stroke-width="1.5"/>
  <circle cx="52" cy="48" r="14" fill="$GLOW" opacity="0.45" filter="url(#glow)"/>
  <circle cx="52" cy="48" r="7.5" fill="url(#led)"/>
  <g transform="translate(132 122) scale(0.8) translate(-128 -128)">
EOF
  mark "$INK"
  echo '  </g>'
}

# Each framing: the XML header, the generated note, then the frame around the mark.
app_icon() {
  printf '%s\n%s\n' '<?xml version="1.0" encoding="UTF-8"?>' "$GENERATED"
  echo '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="1024" height="1024">'
  key_defs
  echo '<g transform="translate(128 128) scale(0.8521) translate(-128 -128)">'
  keycap shadow
  echo '</g>'
  echo '</svg>'
}

site_icon() {
  printf '%s\n%s\n' '<?xml version="1.0" encoding="UTF-8"?>' "$GENERATED"
  echo '<svg xmlns="http://www.w3.org/2000/svg" viewBox="8 8 240 240" width="240" height="240">'
  key_defs
  keycap
  echo '</svg>'
}

# The key on an opaque square with no rounding: every pixel opaque, so iOS's own mask is
# the only rounding a saved icon gets.
touch_icon() {
  printf '%s\n%s\n' '<?xml version="1.0" encoding="UTF-8"?>' "$GENERATED"
  echo '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="180" height="180">'
  key_defs
  echo "  <rect x=\"0\" y=\"0\" width=\"256\" height=\"256\" fill=\"$BACKDROP\"/>"
  keycap shadow
  echo '</svg>'
}

menubar() {
  printf '%s\n%s\n' '<?xml version="1.0" encoding="UTF-8"?>' "$GENERATED"
  echo '<svg xmlns="http://www.w3.org/2000/svg" viewBox="48 48 160 160" width="18" height="18">'
  mark "$MASK"
  echo '</svg>'
}

# The committed SVGs, written under $1 at their paths in the repository.
COMMITTED="packaging/icon.svg packaging/menubar.svg site/icon.svg"
write_svgs() {
  mkdir -p "$1/packaging" "$1/site"
  app_icon >"$1/packaging/icon.svg"
  menubar >"$1/packaging/menubar.svg"
  site_icon >"$1/site/icon.svg"
}

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

if [[ "${1:-}" == "--check" ]]; then
  write_svgs "$WORK"
  stale=0
  for file in $COMMITTED; do
    if ! diff -u "$ROOT/$file" "$WORK/$file"; then
      echo "make-icon: $file is not what scripts/make-icon.sh writes; rerun it" >&2
      stale=1
    fi
  done
  [[ $stale == 0 ]] && echo "make-icon: $COMMITTED are current"
  exit $stale
fi

command -v rsvg-convert >/dev/null || { echo "make-icon: rsvg-convert not found; brew install librsvg" >&2; exit 1; }

write_svgs "$ROOT"
echo "make-icon: wrote $COMMITTED"

SVG="$ROOT/packaging/icon.svg"
SET="$WORK/AppIcon.iconset"
mkdir "$SET"
for size in 16 32 128 256 512; do
  rsvg-convert -w "$size" -h "$size" "$SVG" -o "$SET/icon_${size}x${size}.png"
  rsvg-convert -w $((size * 2)) -h $((size * 2)) "$SVG" -o "$SET/icon_${size}x${size}@2x.png"
done
iconutil -c icns "$SET" -o "$ROOT/packaging/AppIcon.icns"
echo "make-icon: wrote packaging/AppIcon.icns"

touch_icon >"$WORK/touch-icon.svg"
rsvg-convert -w 180 -h 180 "$WORK/touch-icon.svg" -o "$ROOT/site/icon.png"
echo "make-icon: wrote site/icon.png"

MENUBAR="$ROOT/packaging/menubar.svg"
rsvg-convert -w 18 -h 18 "$MENUBAR" -o "$ROOT/packaging/MenuBarIcon.png"
rsvg-convert -w 36 -h 36 "$MENUBAR" -o "$ROOT/packaging/MenuBarIcon@2x.png"
echo "make-icon: wrote packaging/MenuBarIcon.png and MenuBarIcon@2x.png"
